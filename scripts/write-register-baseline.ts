// Original — no upstream. Regeneration script for src/tools/_register-baseline.json (FR-018, BI-022).
// Future BIs that intentionally add, remove, or rename a tool, or change a published descriptor, run
// `npm run baseline:write` and commit the regenerated JSON in the same commit as the registry change.
//
// 068 R3: the fingerprints come from `fingerprintLiveRegistry` in src/tools/_register-baseline.ts — the
// same helper the FR-018 gate in src/tools/_register.test.ts verifies with — so writer and verifier cannot
// drift. The script cannot import that module directly: Node's type stripping does not resolve the project's
// `.js`-on-`.ts` import aliases (NodeNext convention), and vitest is the only runtime the project wires up that
// does. So the script writes a temporary vitest file that calls the helper and dumps the entries to a temp
// JSON file, then wraps them in the baseline envelope here. The write-run-read-clean-up cycle is
// `runVitestDump` in scripts/_vitest-dump.ts, shared with scripts/audit-descriptions.ts.

import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { runVitestDump } from "./_vitest-dump.ts";

// The entries are passed through untouched; their shape is `BaselineEntry` in
// src/tools/_register-baseline.ts, the one definition.
async function fingerprintViaVitest(): Promise<unknown[]> {
  const text = await runVitestDump(
    "__baseline-dumper.test.ts",
    (dumpPath) => `// Auto-generated by scripts/write-register-baseline.ts — safe to delete.
import { writeFileSync } from "node:fs";

import { it } from "vitest";

import { fingerprintLiveRegistry } from "./_register-baseline.js";

it("dump registry fingerprints to ${dumpPath.replaceAll("\\", "\\\\")}", async () => {
  const entries = await fingerprintLiveRegistry();
  writeFileSync(${JSON.stringify(dumpPath)}, JSON.stringify(entries, null, 2) + "\\n");
});
`,
  );
  return JSON.parse(text) as unknown[];
}

async function main(): Promise<void> {
  const entries = await fingerprintViaVitest();

  let branch = "unknown";
  try {
    branch = execSync("git rev-parse --abbrev-ref HEAD", { encoding: "utf8" }).trim();
  } catch {
    // git not available or not a repo — leave branch as "unknown"
  }
  const payload = {
    schemaVersion: 2 as const,
    generatedFromBranch: branch,
    generatedAt: new Date().toISOString().slice(0, 10),
    tools: entries,
  };
  const outPath = resolve(import.meta.dirname, "..", "src", "tools", "_register-baseline.json");
  writeFileSync(outPath, JSON.stringify(payload, null, 2) + "\n", { encoding: "utf8" });
  process.stderr.write(`Wrote ${entries.length} entries to ${outPath}\n`);
}

await main();
