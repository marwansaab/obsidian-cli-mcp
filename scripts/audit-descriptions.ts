// Original — no upstream. npm run audit:descriptions: prints the tool-description audit report (spec 092) as Markdown on stdout, built from the live tool list and the reviewer record by a generated vitest dumper.
//
// The report logic lives in src/tools/_description-audit.ts. Node cannot import it directly (the
// project's `.js`-on-`.ts` specifiers), so a generated vitest file calls it and writes the Markdown to a
// scratch file (`runVitestDump`, shared with the baseline writer). vitest's own output goes to stderr,
// so stdout carries the report alone and can be redirected to a file.

import { execSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

import { runVitestDump } from "./_vitest-dump.ts";

function git(args: string): string {
  return execSync(`git ${args}`, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
}

function localDate(): string {
  const now = new Date();
  const pad = (n: number) => String(n).padStart(2, "0");
  return `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;
}

async function main(): Promise<void> {
  const packageJson = resolve(import.meta.dirname, "..", "package.json");
  const { version } = JSON.parse(readFileSync(packageJson, "utf8")) as { version: string };
  const meta = { version, sha: git("rev-parse --short HEAD"), branch: git("rev-parse --abbrev-ref HEAD"), date: localDate() };

  const report = await runVitestDump(
    "__description-audit-dumper.test.ts",
    (dumpPath) => `// Auto-generated by scripts/audit-descriptions.ts — safe to delete.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { it } from "vitest";

import { collectPublishedSurface, descriptionAuditRecordSchema, renderAuditReport } from "./_description-audit.js";

it("dump the description audit report", async () => {
  const record = descriptionAuditRecordSchema.parse(
    JSON.parse(readFileSync(join(import.meta.dirname, "_description-audit-record.json"), "utf8")),
  );
  const surface = await collectPublishedSurface();
  writeFileSync(${JSON.stringify(dumpPath)}, renderAuditReport(surface, record, ${JSON.stringify(meta)}));
});
`,
  );
  process.stdout.write(report);
}

try {
  await main();
} catch (err) {
  process.stderr.write(`audit:descriptions failed: ${err instanceof Error ? err.message : String(err)}\n`);
  process.exitCode = 1;
}
